// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board ranks every pre-token protocol the snapshot's own watchlist rule would keep: the 40
// watchlist protocols (the floor, never a ceiling) plus every other protocol below the floor that
// records no token and is not a wrapped, staked or bridged product of a token that already trades.
// A protocol is pre-token when its record carries no market cap, no CoinGecko id and no symbol.
// Protocols whose token already trades are kept apart in the dashboard's Live view, shown at the
// market's own value, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures, never from a hand-kept list of names:
//
//   categoryRatio = median(mcap_usd / tvl_usd) over the snapshot's tokenised protocols in the same
//                   category (at least 3 samples, else the global median over all tokenised
//                   protocols); clamped to [0.05, 25]. This is the market's own answer to "what is a
//                   protocol of this kind worth per dollar of TVL".
//   growthMult    = 1 + clamp(change_7d, -50, 100) / 100 * 0.5
//   maturityMult  = 0.7 + min(age_days, 1095) / 1095 * 0.5   (age unknown: 365 days)
//   impliedFdv    = tvl_usd * categoryRatio * growthMult * maturityMult
//   impliedValue  = round(impliedFdv * 0.10)
//
// The 10% is the community's share at launch: the slice of the implied fully-diluted value a
// farmer's airdrop would come out of. The dashboard states the formula in full, with each row's
// own numbers, so a reader can check every rank by hand.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

